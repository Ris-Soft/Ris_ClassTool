const fs = require('fs');
const path = require('path');

// 创建一个简单的16x16 ICO文件
const icoData = Buffer.from([
  0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x10, 0x10, 0x00, 0x00, 0x01, 0x00,
  0x20, 0x00, 0x68, 0x04, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x28, 0x00,
  0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x01, 0x00,
  0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00
]);

// 填充剩余数据创建一个蓝色图标
const fullIcoData = Buffer.alloc(1150);
icoData.copy(fullIcoData);

// 添加蓝色像素数据
for (let i = 54; i < 1150; i += 4) {
  fullIcoData[i] = 0xFF;     // Blue
  fullIcoData[i + 1] = 0x80; // Green
  fullIcoData[i + 2] = 0x00; // Red
  fullIcoData[i + 3] = 0xFF; // Alpha
}

fs.writeFileSync(path.join(__dirname, 'tray-icon.ico'), fullIcoData);
console.log('托盘图标已创建');